/* Rebuild the nested result shape from a flat history record so the
   module panels can render a replay without crashing on undefined data. */

function flatRecordToResult(record) {
  const score = (v, fallback = 0) => (typeof v === "number" && Number.isFinite(v) ? v : fallback);
  return {
    id: record.id,
    filename: record.filename,
    word_count: record.word_count,
    section_count: 0,
    sections: [],
    overall_research_credibility: score(record.overall_research_credibility),
    verdict: record.verdict,
    report_path: record.report_path,
    analyzed_at: record.analyzed_at,
    action_items: [],
    risk_triggers: [],
    plagiarism: {
      score: score(record.plagiarism_score),
      summary: "Replay of a stored analysis — detailed source matches are not kept after the original scan completes (papers are never permanently stored).",
      matches: [],
      duplicate_paragraphs: 0,
    },
    ai_detection: {
      ai_probability: score(record.ai_probability),
      confidence: record.ai_confidence,
      engine: record.ai_engine,
    },
    citation: {
      validity_score: score(record.citation_validity_score),
      summary: "Replay of a stored analysis — per-reference details are not kept after the original scan completes.",
      total_dois: 0,
      valid_dois: 0,
      invalid_dois: [],
      references_without_doi: 0,
      verified_dois: [],
    },
    statistics: {
      risk_score: 100 - score(record.statistical_risk_score),
      summary: "Replay of a stored analysis — numeric findings are not kept after the original scan completes.",
      findings: [],
    },
    writing: {
      score: score(record.writing_quality_score),
      checks: [],
    },
    provenance: buildReplayProvenance(record),
  };
}

function buildReplayProvenance(record) {
  const score = (v, fallback) => (typeof v === "number" && Number.isFinite(v) ? v : fallback);
  const details = record.provenance_details || {};
  if (record.provenance_score == null && !details) return null;
  return {
    score: score(record.provenance_score, 50),
    summary:
      details.summary ||
      "Replay of a stored analysis — detailed provenance evidence is not kept after the original scan completes.",
    contamination_score: details.contamination_score ?? 50,
    graph_anomaly_score: details.graph_anomaly_score ?? 50,
    alignment_score: details.alignment_score ?? 50,
    fingerprint_score: details.fingerprint_score ?? 50,
    contamination_summary: details.contamination_summary || "",
    retracted_dois: details.retracted_dois || [],
    alignment_verdicts: details.alignment_verdicts || [],
    fingerprint_notes: details.fingerprint_notes || {},
    graph_density: details.graph_density || 0,
    isolated_references: details.isolated_references || 0,
    web_matches: details.web_matches || [],
    web_summary: details.web_summary || "",
    web_available: details.web_available === true,
  };
}

export default function App() {
  const [file, setFile] = useState(null);
  const [loading, setLoading] = useState(false);
  const [progress, setProgress] = useState(0);
  const [result, setResult] = useState(null);
  const [error, setError] = useState("");
  const [openModule, setOpenModule] = useState("ai_detection");
  const [config, setConfig] = useState(null);
  const [serverHistory, setServerHistory] = useState([]);
  const [localHistory] = useState(getHistory());
  const [showOnboard, setShowOnboard] = useState(false);
  const [replayError, setReplayError] = useState("");
  const [replayLoading, setReplayLoading] = useState(false);

  const modulePanelFallback = () => (
    <div className="p-6 text-center">
      <p className="text-sm font-medium text-slate-900">This detail could not be shown</p>
      <p className="text-xs text-slate-500 mt-2 max-w-md mx-auto">
        The detailed data for this older analysis is not kept on the server (papers are never stored). The overview scores above are still accurate — for a full replay, re-upload the paper.
      </p>
    </div>
  );

  useEffect(() => {
    fetchConfig().then(setConfig).catch(() => {});
    fetchHistory()
      .then((data) => setServerHistory(Array.isArray(data) ? data : data?.results ?? []))
      .catch(() => {});
    if (!localStorage.getItem("veripaper_onboarded")) {
      setShowOnboard(true);
    }
  }, []);

  const modules = useMemo(() => {
    if (!result) return [];
    return [
      { key: "plagiarism", score: result.plagiarism?.score ?? 0, invert: true },
      { key: "ai_detection", score: result.ai_detection?.ai_probability ?? 0 },
      { key: "citation", score: result.citation?.validity_score ?? 0 },
      { key: "statistics", score: 100 - (result.statistics?.risk_score ?? 0), invert: true },
      { key: "writing", score: result.writing?.score ?? 0 },
      { key: "provenance", score: result.provenance?.score ?? 0 },
    ];
  }, [result]);

  const vMeta = useMemo(() => (result ? verdictMeta(result.verdict) : null), [result]);

  const runAnalysis = async (e) => {
    e.preventDefault();
    if (!file) { setError("Please select a paper first (PDF, DOCX or TXT)."); return; }
    if (file.size > 15 * 1024 * 1024) { setError("File is larger than 15 MB."); return; }
    setError("");
    setLoading(true);
    setResult(null);
    setProgress(8);

    const timers = [];
    try {
      // Start async analysis
      setProgress(10);
      const { task_id } = await analyzePaperAsync(file);

      // Poll for completion with progress feedback
      const resultData = await pollUntilDone(
        task_id,
        (status) => {
          if (status.status === "queued") setProgress(15);
          else if (status.status === "processing") setProgress(50);
        },
        800,
        120000
      );

      const data = resultData.result;
      setProgress(100);
      setResult(data);
      saveToHistory(data);
      setServerHistory((prev) => [
        { id: `analysis_${Date.now()}`, filename: data.filename, analyzed_at: new Date().toISOString(), overall_research_credibility: data.overall_research_credibility, verdict: data.verdict },
        ...prev,
      ].slice(0, 15));
      setOpenModule("ai_detection");
    } catch (err) {
      setError(friendlyError(err, "Analysis failed. Please try again."));
    } finally {
      timers.forEach(clearTimeout);
      setLoading(false);
    }
  };

  /* Convert any API error payload into a human-readable string, so the
     UI never shows a raw "[object Object]" from FastAPI validation lists. */
  const friendlyError = (err, fallback) => {
    const raw = err?.response?.data?.detail ?? err?.message ?? fallback;
    if (typeof raw === "string") return raw;
    if (Array.isArray(raw)) {
      // FastAPI validation errors: [{loc, msg, type}, ...]
      const first = raw[0];
      if (first && typeof first.msg === "string") return first.msg;
      return String(raw[0] ?? fallback);
    }
    if (raw && typeof raw.msg === "string") return raw.msg;
    if (raw && typeof raw.detail === "string") return raw.detail;
    return fallback;
  };

  const openOld = async (entry) => {
    setError("");
    setReplayError("");
    // Only server-side rows have numeric ids; local/browser copies and the
    // ephemeral preview rows use string ids that the API cannot resolve.
    const recordId = Number(entry.id);
    if (!Number.isFinite(recordId)) {
      setReplayError("This entry was saved in your browser only — re-upload the paper for a fresh verification.");
      return;
    }
    setReplayLoading(true);
    try {
      const record = await fetchHistoryItem(recordId);
      setResult(flatRecordToResult(record));
      setOpenModule("ai_detection");
    } catch (err) {
      setReplayError(friendlyError(err, "Could not open this analysis. Re-upload the paper for a fresh verification."));
    } finally {
      setReplayLoading(false);
    }
  };

  return (
    <div className="min-h-screen bg-slate-50">
      {/* Header */}
      <header className="sticky top-0 z-40 bg-white/90 backdrop-blur border-b border-slate-200">
        <div className="max-w-6xl mx-auto px-4 sm:px-6 h-16 flex items-center justify-between">
          <div className="flex items-center gap-3">
            <div className="w-9 h-9 rounded-lg bg-gradient-to-br from-blue-600 to-indigo-700 text-white font-bold flex items-center justify-center">V</div>
            <div>
              <p className="font-bold text-slate-900 leading-tight">VeriPaper</p>
              <p className="text-[11px] text-slate-500 leading-tight">Research Verification Suite</p>
            </div>
          </div>
          <nav className="hidden sm:flex items-center gap-1 text-sm">
            <a href="#analyze" className="px-3 py-2 rounded-lg text-slate-600 hover:bg-slate-100">Analyze</a>
            <a href="#history" className="px-3 py-2 rounded-lg text-slate-600 hover:bg-slate-100">History</a>
            <a href="#method" className="px-3 py-2 rounded-lg text-slate-600 hover:bg-slate-100">How it works</a>
          </nav>
        </div>
      </header>

      <main className="max-w-6xl mx-auto px-4 sm:px-6 py-8 space-y-8">
        {/* Hero */}
        <section className="text-center max-w-2xl mx-auto">
          <span className="inline-block text-xs font-semibold px-3 py-1 rounded-full bg-blue-100 text-blue-700 mb-4">
            ✦ VeriPaper — the 6-in-1 integrity check
          </span>
          <h1 className="text-3xl sm:text-4xl font-black text-slate-900 tracking-tight">
            Is your research paper really <span className="text-blue-600">credible?</span>
          </h1>
          <p className="text-slate-600 mt-3">
            One upload. Six checks: plagiarism, AI authorship, citation authenticity, statistical integrity, academic writing standards, and provenance-chain verification — every result explained in plain language.
          </p>
        </section>

        {/* Upload */}
        <section id="analyze" className="card bg-white border border-slate-200 shadow-sm">
          <form onSubmit={runAnalysis} className="space-y-4">
            <label className="flex flex-col items-center justify-center border-2 border-dashed border-slate-300 rounded-xl p-8 text-center cursor-pointer hover:border-blue-500 hover:bg-blue-50/40 transition-colors">
              <input type="file" accept=".pdf,.docx,.txt" className="hidden" onChange={(e) => setFile(e.target.files?.[0] || null)} />
              <span className="text-3xl">📄</span>
              <p className="font-semibold text-slate-900 mt-2 text-sm break-all">{file ? file.name : "Drop your paper here, or click to browse"}</p>
              <p className="text-xs text-slate-500 mt-1">PDF, DOCX, or TXT · max 15 MB · processed privately, never shared</p>
            </label>
            {error && <p className="text-xs font-medium text-red-700 bg-red-50 border border-red-200 rounded-lg p-3">⚠ {error}</p>}
            {loading && (
              <div className="space-y-2">
                <div className="flex justify-between text-xs text-slate-600">
                  <span>Analyzing… (parsing · AI model · similarity corpus · CrossRef)</span>
                  <span>{Math.round(progress)}%</span>
                </div>
                <ProgressBar value={progress} color="bg-blue-500" />
              </div>
            )}
            <button type="submit" disabled={loading || !file} className="w-full btn-primary disabled:opacity-50 disabled:cursor-not-allowed">
              {loading ? "Analyzing…" : "Run Full Verification"}
            </button>
          </form>
        </section>

        {/* Results */}
        {result && (
          <section className="space-y-6">
            {/* Verdict banner */}
            <div className="card bg-white border border-slate-200 shadow-sm">
              <div className="flex flex-col sm:flex-row items-center gap-6">
                <GradeGauge score={result.overall_research_credibility} size={110} />
                <div className="flex-1 text-center sm:text-left">
                  <p className="text-xs uppercase tracking-wider text-slate-500 font-semibold mb-1">Overall credibility</p>
                  <h2 className="text-2xl font-bold text-slate-900">{vMeta.title}</h2>
                  <p className="text-sm text-slate-600 mt-2 max-w-xl">{vMeta.desc}</p>
                  <div className="mt-3 flex flex-wrap gap-2 justify-center sm:justify-start">
                    <span className={`text-xs px-2.5 py-1 rounded-full border font-medium ${vMeta.badge}`}>{result.verdict}</span>
                    <span className="text-xs px-2.5 py-1 rounded-full bg-slate-100 text-slate-600">{result.word_count} words · {result.section_count} sections · {result.filename}</span>
                  </div>
                </div>
              </div>
              {(result.action_items?.length > 0 || result.risk_triggers?.length > 0) && (
                <div className="mt-5 border-t border-slate-100 pt-4">
                  <p className="text-xs font-semibold text-slate-500 uppercase tracking-wide mb-2">Recommended next steps</p>
                  <ol className="space-y-1.5">
                    {result.action_items.map((item, i) => (
                      <li key={i} className="flex gap-2 text-sm text-slate-700">
                        <span className="font-semibold text-blue-600">{i + 1}.</span> {item}
                      </li>
                    ))}
                  </ol>
                </div>
              )}
            </div>

            {/* Module score tabs */}
            <div className="grid grid-cols-5 gap-2">
              {modules.map((m) => {
                const r = riskLabel(m.score);
                const active = openModule === m.key;
                return (
                  <button
                    key={m.key}
                    onClick={() => setOpenModule(m.key)}
                    className={`card text-center py-3 px-1 border transition-colors ${active ? "border-blue-500 ring-1 ring-blue-500 bg-blue-50/40" : "bg-white border-slate-200 hover:border-slate-300"}`}
                  >
                    <p className="text-[11px] font-semibold text-slate-500 leading-tight">{MODULE_TITLES[m.key]}</p>
                    <p className={`text-lg font-bold leading-tight mt-1 ${r.cls}`}>{Math.round(m.score)}</p>
                    <p className={`text-[10px] leading-tight mt-0.5 ${r.cls}`}>{r.text}</p>
                  </button>
                );
              })}
            </div>

            {/* Module detail */}
            <ErrorBoundary fallback={modulePanelFallback}>
            <div className="card bg-white border border-slate-200 shadow-sm">
              <div className="flex items-start justify-between flex-wrap gap-3 border-b border-slate-100 pb-4 mb-4">
                <div>
                  <h3 className="font-bold text-slate-900">{MODULE_TITLES[openModule]}</h3>
                  <p className="text-xs text-slate-500 mt-1 max-w-xl">{MODULE_EXPLAIN[openModule]}</p>
                </div>
                <span className="text-xs font-semibold text-slate-500 uppercase tracking-wide">
                  {openModule === "statistics" ? "Integrity: " : openModule === "citation" || openModule === "writing" || openModule === "provenance" ? "Score: " : "Risk: "}
                  {Math.round(modules.find((m) => m.key === openModule).score)} / 100
                </span>
              </div>
              {openModule === "plagiarism" && <PlagiarismPanel data={result.plagiarism} />}
              {openModule === "ai_detection" && <AIPanel data={result.ai_detection} />}
              {openModule === "citation" && <CitationPanel data={result.citation} />}
              {openModule === "statistics" && <StatisticsPanel data={result.statistics} />}
              {openModule === "writing" && <WritingPanel data={result.writing} />}
              {openModule === "provenance" && <ProvenancePanel data={result.provenance} />}
            </div>
            </ErrorBoundary>

            {/* Sections & exports */}
            <div className="grid lg:grid-cols-[1fr_320px] gap-6">
              <div className="card bg-white border border-slate-200 shadow-sm">
                <h3 className="font-bold text-slate-900 mb-3 text-sm">Detected structure</h3>
                <div className="flex flex-wrap gap-2">
                  {result.sections.map((s, i) => (
                    <div key={i} className="text-xs px-2.5 py-1.5 bg-slate-50 border border-slate-200 rounded-lg">
                      <span className="font-medium text-slate-800">{s.heading}</span>
                      <span className="text-slate-500"> · {s.word_count}w</span>
                    </div>
                  ))}
                </div>
              </div>
              <div className="card bg-white border border-slate-200 shadow-sm space-y-3">
                <h3 className="font-bold text-slate-900 text-sm">Export evidence</h3>
                <button onClick={() => downloadPDF(result.report_path)} className="btn-primary w-full text-sm">📥 PDF Report</button>
                <button onClick={() => downloadCSV(result)} className="btn-secondary w-full text-sm">CSV Export</button>
                <button onClick={() => downloadJSON(result)} className="btn-secondary w-full text-sm">JSON Export</button>
              </div>
            </div>
          </section>
        )}

        {/* History */}
        <section id="history" className="card bg-white border border-slate-200 shadow-sm">
          <h3 className="font-bold text-slate-900 mb-4">Analysis history</h3>
          {serverHistory.length === 0 ? (
            <p className="text-sm text-slate-500 py-8 text-center">No analyses yet — your first verification will appear here.</p>
          ) : (
            <div className="space-y-2">
              {serverHistory.map((h, i) => (
                <button
                  key={h.id || i}
                  onClick={() => openOld(h)}
                  className="w-full text-left flex items-center justify-between p-3 bg-slate-50 rounded-lg border border-slate-200 hover:border-blue-300 hover:bg-blue-50 transition-colors disabled:opacity-60"
                  disabled={replayLoading}
                >
                  <div>
                    <p className="text-sm font-medium text-slate-900">{h.filename}</p>
                    <p className="text-[11px] text-slate-500 mt-0.5">{new Date(h.analyzed_at).toLocaleString()}</p>
                  </div>
                  <span className="text-xs font-semibold text-slate-600">{Math.round(h.overall_research_credibility)}% · {h.verdict}</span>
                </button>
              ))}
            </div>
          )}
          {replayError && (
            <p className="text-xs text-red-600 bg-red-50 border border-red-200 rounded-lg p-3 mt-3">{replayError}</p>
          )}
          {replayLoading && (
            <p className="text-xs text-slate-500 mt-3">Opening previous analysis…</p>
          )}
          {localHistory.length > 0 && (
            <p className="text-[11px] text-slate-400 mt-3">Also saved locally in this browser ({localHistory.length} entries).</p>
          )}
        </section>

        {/* How it works */}
        <section id="method" className="space-y-4">
          <h3 className="font-bold text-slate-900 text-lg">How VeriPaper verifies a paper</h3>
          <div className="grid md:grid-cols-2 lg:grid-cols-3 gap-4">
            {Object.entries(MODULE_EXPLAIN).map(([key, text]) => (
              <div key={key} className="card bg-white border border-slate-200">
                <p className="text-sm font-bold text-slate-900">{MODULE_TITLES[key]}</p>
                <p className="text-xs text-slate-600 mt-2 leading-relaxed">{text}</p>
              </div>
            ))}
          </div>
          <div className="card bg-amber-50 border border-amber-200 text-xs text-amber-800 p-4">
            <span className="font-semibold">Important:</span> every score is a likelihood signal generated by statistical models — not legal proof of misconduct. Use VeriPaper to triage and prioritize manual review, never as the sole basis for an accusation.
          </div>
        </section>
      </main>

      {/* Footer */}
      <footer className="border-t border-slate-200 bg-white py-8 mt-8">
        <div className="max-w-6xl mx-auto px-4 sm:px-6 flex flex-col sm:flex-row items-center justify-between gap-3 text-xs text-slate-500">
          <p>© 2026 VeriPaper — Research Verification Suite</p>
          {config?.ai_detection && (
            <p>AI model: {config.ai_detection.model_version?.split("/").pop() || config.ai_detection.model_version} (validation F1 {config.ai_detection.metrics?.f1})</p>
          )}
        </div>
      </footer>

      {/* Onboarding */}
      {showOnboard && (
        <div className="fixed inset-0 bg-black/40 backdrop-blur-sm z-50 flex items-center justify-center p-4" onClick={() => { setShowOnboard(false); localStorage.setItem("veripaper_onboarded", "1"); }}>
          <div className="bg-white rounded-2xl shadow-xl max-w-md w-full p-6" onClick={(e) => e.stopPropagation()}>
            <h3 className="text-lg font-bold text-slate-900">Welcome to VeriPaper 👋</h3>
            <p className="text-sm text-slate-600 mt-2">Upload any research paper (PDF/DOCX/TXT) and we'll check five things at once:</p>
            <ul className="mt-3 space-y-1.5 text-sm text-slate-700">
              {Object.values(MODULE_TITLES).map((t, i) => (
                <li key={i} className="flex gap-2"><span className="text-blue-600 font-bold">{i + 1}.</span> {t}</li>
              ))}
            </ul>
            <p className="text-xs text-slate-500 mt-4">Scores are signals to guide review — not proof.</p>
            <button
              onClick={() => { setShowOnboard(false); localStorage.setItem("veripaper_onboarded", "1"); }}
              className="btn-primary w-full mt-4"
            >
              Got it — start analyzing
            </button>
          </div>
        </div>
      )}
    </div>
  );
}
