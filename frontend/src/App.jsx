function verdictMeta(verdict) {
  return VERDICT_META[verdict] || { badge: "bg-slate-100 text-slate-700 border-slate-200", title: verdict || "Pending", desc: "Analysis complete." };
}

function riskLabel(score, invert = false) {
  const v = invert ? 100 - score : score;
  if (v < 30) return { text: "Low concern", cls: "text-emerald-700", bar: "bg-emerald-500" };
  if (v < 60) return { text: "Moderate", cls: "text-amber-700", bar: "bg-amber-500" };
  return { text: "High concern", cls: "text-red-700", bar: "bg-red-500" };
}

