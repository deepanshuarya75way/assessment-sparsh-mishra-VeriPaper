class ErrorBoundary extends Component {
  constructor(props) {
    super(props);
    this.state = { err: null };
  }
  static getDerivedStateFromError(err) {
    return { err };
  }
  render() {
    if (this.state.err) {
      return (this.props.fallback || (() => null))(this.state.err);
    }
    return this.props.children;
  }
}

